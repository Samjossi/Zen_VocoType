"""协议错误码。

错误响应统一形态::

    {"ok": false, "error": {"code": <int>, "message": <str>}}

错误码区间划分（区间即语义，新增错误码必须落入对应区间）：

- 1xxx 协议层错误（帧格式、版本、未知 action）
- 2xxx 服务状态错误（未就绪、忙碌）
- 3xxx 模型错误（未找到、加载/切换失败）
- 4xxx 识别错误（音频非法、推理失败、audio_chunk 会话错误）
"""

# ---------------------------------------------------------------------------
# 1xxx 协议层错误
# ---------------------------------------------------------------------------

#: 帧格式非法（长度前缀异常、JSON 头解析失败等）
ERR_MALFORMED_FRAME: int = 1001

#: 未知 action
ERR_UNKNOWN_ACTION: int = 1002

#: 协议版本不兼容（握手时 MAJOR.MINOR 不一致）
ERR_PROTOCOL_VERSION_MISMATCH: int = 1003

#: 请求头缺少必填字段
ERR_MISSING_FIELD: int = 1004

#: action 已定义但本端版本未实现（如 v1 收到 audio_chunk）；
#: 与 1002（未知 action）区分：调用方收到本错误码不应按「请求有误」修正重试
ERR_ACTION_NOT_SUPPORTED: int = 1005

#: 对端身份校验失败（SO_PEERCRED UID 不在白名单，见 paths.py 安全约定 4）
ERR_UNAUTHORIZED_PEER: int = 1006

# ---------------------------------------------------------------------------
# 2xxx 服务状态错误
# ---------------------------------------------------------------------------

#: 服务未就绪（模型仍在加载，收到 recognize 等需要就绪状态的请求）
ERR_NOT_READY: int = 2001

#: 服务忙碌（如正在切换模型时的并发请求）
ERR_BUSY: int = 2002

# ---------------------------------------------------------------------------
# 3xxx 模型错误
# ---------------------------------------------------------------------------

#: 请求的模型不存在于模型注册表
ERR_MODEL_NOT_FOUND: int = 3001

#: 模型加载失败
ERR_MODEL_LOAD_FAILED: int = 3002

#: 模型切换失败（切换后 model_info 校验不通过等）
ERR_MODEL_SWITCH_FAILED: int = 3003

# ---------------------------------------------------------------------------
# 4xxx 识别错误
# ---------------------------------------------------------------------------

#: 音频参数非法或与声明不符（采样率/声道/字节数校验失败）
ERR_INVALID_AUDIO: int = 4001

#: 推理执行失败
ERR_RECOGNITION_FAILED: int = 4002

#: audio_chunk 会话状态非法：会话不存在/已销毁/begin 重复/data 缺会话/seq 乱序跳号重复
ERR_SESSION_STATE: int = 4003

#: audio_chunk 会话累计音频超服务端上限（chunk_session_max_bytes）
ERR_SESSION_TOO_LARGE: int = 4004
